//numeros.js - metodos de Math y Number.
console.log(Math.round(4.6)); //Redondea: 5.
console.log(Math.floor(4.6)); //Hacia abajo: 4.
console.log(Math.ceil(4.2)); //Hacia arriba: 5.
console.log(Math.max(45000, 75000, 38000)); //El mayor = 75000.
console.log(Math.min(45000, 75000, 38000)); //El menor = 38000.
console.log(Number.isInteger(2.75)); //Es entero? = false.
